// Files that serve a folder of generated pages from nginx, behind a login by
// default. Plain files, no vibeX at runtime: the container is nginx and the
// HTML, so it runs anywhere Docker does (a VPS, Railway, Fly, a laptop).

export const HOST_MARKER = 'Generated by vibeX (vibex host)';
export const HOST_DIR = '.vibex-host';

const dockerfile = `# ${HOST_MARKER}. Re-run "vibex host" to update it.
FROM nginx:1.27-alpine
ENV PORT=8080
COPY ${HOST_DIR}/default.conf.template /etc/nginx/templates/default.conf.template
COPY ${HOST_DIR}/40-vibex-auth.sh /docker-entrypoint.d/40-vibex-auth.sh
COPY . /usr/share/nginx/html
RUN chmod 755 /docker-entrypoint.d/40-vibex-auth.sh \\
 && rm -rf /usr/share/nginx/html/${HOST_DIR} /usr/share/nginx/html/Dockerfile /usr/share/nginx/html/docker-compose.yml
EXPOSE 8080
`;

// \${PORT} is filled by the nginx image's envsubst step; nginx's own $uri is
// left alone because no environment variable has that name.
const nginxConf = `# ${HOST_MARKER}.
server {
  listen \${PORT};
  server_name _;
  root /usr/share/nginx/html;
  index index.html dashboard.html;
  server_tokens off;
  charset utf-8;
  gzip on;
  gzip_types text/css application/javascript application/json image/svg+xml;
  add_header X-Content-Type-Options nosniff always;
  add_header X-Frame-Options SAMEORIGIN always;
  add_header Referrer-Policy no-referrer always;

  # Unauthenticated, so a platform health check does not need the password.
  location = /healthz { auth_basic off; access_log off; default_type text/plain; return 200 "ok\\n"; }
  location ~ /\\. { deny all; }
  location / {
    include /etc/nginx/vibex-auth.conf;
    try_files $uri $uri/ $uri.html =404;
  }
}
`;

const authScript = `#!/bin/sh
# ${HOST_MARKER}.
# The login is on unless VIBEX_PUBLIC=1 says otherwise. Missing credentials
# stop the container rather than serving the docs to anyone who finds the URL.
set -eu
conf=/etc/nginx/vibex-auth.conf
if [ "\${VIBEX_PUBLIC:-}" = "1" ]; then
  echo 'auth_basic off;' > "$conf"
  echo "vibex: VIBEX_PUBLIC=1, serving without a login" >&2
  exit 0
fi
if [ -z "\${VIBEX_USER:-}" ] || [ -z "\${VIBEX_PASSWORD:-}" ]; then
  echo "vibex: set VIBEX_USER and VIBEX_PASSWORD, or VIBEX_PUBLIC=1 to serve without a login" >&2
  exit 1
fi
case "$VIBEX_USER" in *:*) echo "vibex: VIBEX_USER cannot contain ':'" >&2; exit 1 ;; esac
hash=$(printf '%s' "$VIBEX_PASSWORD" | mkpasswd -m sha512 -P 0)
printf '%s:%s\\n' "$VIBEX_USER" "$hash" > /etc/nginx/vibex.htpasswd
chown root:nginx /etc/nginx/vibex.htpasswd
chmod 640 /etc/nginx/vibex.htpasswd
printf 'auth_basic "%s";\\nauth_basic_user_file /etc/nginx/vibex.htpasswd;\\n' "\${VIBEX_REALM:-Docs}" > "$conf"
`;

const compose = `# ${HOST_MARKER}.
# VIBEX_USER=you VIBEX_PASSWORD=secret docker compose up --build
services:
  docs:
    build: .
    ports:
      - "\${VIBEX_HOST_PORT:-8080}:8080"
    environment:
      VIBEX_USER: \${VIBEX_USER:-}
      VIBEX_PASSWORD: \${VIBEX_PASSWORD:-}
      VIBEX_PUBLIC: \${VIBEX_PUBLIC:-}
    restart: unless-stopped
`;

const dockerignore = `# ${HOST_MARKER}.
.git
**/.git
`;

// path (relative to the served folder) -> contents
export function hostFiles() {
  return {
    Dockerfile: dockerfile,
    'docker-compose.yml': compose,
    '.dockerignore': dockerignore,
    [`${HOST_DIR}/default.conf.template`]: nginxConf,
    [`${HOST_DIR}/40-vibex-auth.sh`]: authScript,
  };
}

export function isOurs(text) {
  return String(text || '').includes(HOST_MARKER);
}
