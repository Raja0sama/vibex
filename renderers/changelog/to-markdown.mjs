// The changelog as Markdown, in the same portable subset the docs use: no raw
// HTML, because this file gets pasted into release notes, a wiki, and a Slack
// message, and an unrendered tag is worse than a plain sentence.

const SECTION_NOTE = {
  breaking: 'Read these before upgrading.',
  internal: 'Nothing here changes how the tool behaves.',
};

// A list of ids stops being information somewhere around a dozen.
const CAP = 12;
function ids(list) {
  const shown = list.slice(0, CAP).map((id) => `\`${id}\``).join(', ');
  return list.length > CAP ? `${shown}, and ${list.length - CAP} more` : shown;
}

function commitLink(entry, repository) {
  const url = repository?.url?.replace(/\/+$/, '').replace(/\.git$/, '');
  if (!url || !/^https?:\/\/(www\.)?(github|gitlab)\.com\//i.test(url)) return `\`${entry.short}\``;
  const path = /gitlab\.com/i.test(url) ? '/-/commit/' : '/commit/';
  return `[\`${entry.short}\`](${url}${path}${entry.commit})`;
}

function entryLine(entry, repository) {
  const bits = [`- ${entry.title}`];
  if (entry.scope) bits.push(` *(${entry.scope})*`);
  bits.push(` — ${commitLink(entry, repository)}`);
  if (entry.specs?.length) bits.push(`, touching ${entry.specs.map((s) => `\`${s}\``).join(', ')}`);
  return bits.join('');
}

export function changelogToMarkdown(log, { repository = null, title = null } = {}) {
  const byId = new Map(log.entries.map((e) => [e.commit, e]));
  const out = [];
  const push = (...lines) => out.push(...lines);

  const { from, to, from_commit: fromCommit, to_commit: toCommit } = log.range;
  push(`# ${title || `Changes in ${to}`}`);
  push('', from
    ? `Everything between \`${from}\` and \`${to}\`${fromCommit && toCommit ? ` (\`${fromCommit.slice(0, 7)}\`…\`${toCommit.slice(0, 7)}\`)` : ''}.`
    : `Everything up to \`${to}\`.`);

  const { commits, authors, specs_changed: specs, grouping, claims } = log.impact;
  push('', `${commits} commit${commits === 1 ? '' : 's'}`
    + `${authors.length ? ` from ${authors.length} author${authors.length === 1 ? '' : 's'}` : ''}`
    + `${specs.length ? `, touching ${specs.length} spec${specs.length === 1 ? '' : 's'}` : ''}.`);

  // Say when the grouping is the tool's guess. A reader who believes these
  // headings were chosen deliberately will draw conclusions from them.
  if (grouping === 'inferred') {
    push('', '> Sections below were inferred from the files each commit touched, not from the commit'
      + ' messages — this history does not use conventional-commit prefixes. Treat the grouping as a'
      + ' rough sort, not as the author’s intent.');
  }

  for (const section of log.sections) {
    push('', `## ${section.title}`);
    if (SECTION_NOTE[section.id]) push('', `*${SECTION_NOTE[section.id]}*`);
    push('');
    push(section.entries.map((id) => entryLine(byId.get(id), repository)).filter(Boolean).join('\n'));
  }

  if (claims) {
    const { added = [], removed = [], superseded = [], reworded = [],
      derived_added: derivedAdded = 0, derived_removed: derivedRemoved = 0 } = claims;
    const authoredTotal = added.length + removed.length + superseded.length + reworded.length;
    push('', '## What this did to the documentation', '');
    if (!authoredTotal && !derivedAdded && !derivedRemoved) {
      push('- Nothing. No claim was added, removed, reworded or superseded.');
    } else {
      if (added.length) push(`- **${added.length} claim${added.length === 1 ? '' : 's'} written**: ${ids(added)}`);
      if (reworded.length) push(`- **${reworded.length} reworded**: ${ids(reworded.map((c) => c.id))}`);
      if (superseded.length) push(`- **${superseded.length} superseded**: ${superseded.map((c) => `\`${c.id}\` replaces \`${c.replaces}\``).join(', ')}`);
      // Removal is the one that deserves a reader's attention: a claim that
      // simply vanished took whatever it documented with it.
      if (removed.length) push(`- **${removed.length} removed**: ${ids(removed)} — check these were meant to go, not lost in a rewrite.`);
      if (derivedAdded || derivedRemoved) {
        push(`- ${derivedAdded ? `${derivedAdded} derived fact${derivedAdded === 1 ? '' : 's'} appeared` : ''}`
          + `${derivedAdded && derivedRemoved ? ' and ' : ''}`
          + `${derivedRemoved ? `${derivedRemoved} disappeared` : ''}`
          + ' as the diagrams changed. These are computed, not written, so they are not listed.');
      }
    }
  }

  if (specs.length) {
    push('', '## Specs touched', '');
    push(specs.map((s) => `- \`${s}\``).join('\n'));
  }

  push('', '---', '');
  push(`<sub>Generated by ${log.generator} from commit history on ${log.generated_at}.</sub>`);
  return `${out.join('\n')}\n`;
}
