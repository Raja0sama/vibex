// The same fact graph as a Markdown file.
//
// This is the copy that travels: into a repository, into Confluence, into a
// wiki, into whatever someone pastes it in. So it uses no raw HTML — not
// `<sub>`, not `<a id>`, not `<br>` — because the renderer on the other side is
// unknown and an unrendered tag is worse than a plain sentence. Only headings,
// paragraphs, lists, blockquotes, tables, code and emphasis, which every
// Markdown dialect in use agrees on.
//
// It is not a transcript of the panel either: the panel can hide evidence
// behind a disclosure, a file cannot. Every claim appears, and every claim
// keeps the confidence it earned, because this copy is the one most likely to
// be read far from the build that produced it.

const MARK = { verified: '✓', proposed: '~', asserted: '·', stale: '!', broken: '✗', expired: '!' };
const NOTE = {
  verified: 'verified against the code',
  proposed: 'proposed — describes something that does not exist',
  asserted: 'stated by a person',
  stale: 'needs re-reading',
  broken: 'unverifiable',
  expired: 'out of date',
};

function sourceNote(claim, repository) {
  const s = claim.source || {};
  if (s.kind === 'derived') return `computed from \`${s.spec}\` by \`${s.rule}\``;
  if (s.kind === 'anchored') {
    const where = `${s.path}${s.symbol ? ` › ${s.symbol}` : ''}`;
    const url = repository?.url?.replace(/\/$/, '');
    if (!url) return `\`${where}\``;
    const line = Number.isInteger(s.line) ? `#L${s.line}` : '';
    return `[\`${where}\`](${url}/blob/${repository.revision || 'HEAD'}/${s.path}${line})`;
  }
  if (s.kind === 'asserted') return `stated by ${s.by} on ${s.at}`;
  return '';
}

function claimBullet(claim, repository) {
  const conf = claim.confidence || 'verified';
  const tail = [NOTE[conf] || conf, sourceNote(claim, repository)].filter(Boolean).join(' — ');
  const detail = claim.detail ? ` ${claim.detail}.` : '';
  // Two trailing spaces is the one portable line break in Markdown.
  return `- ${MARK[conf] || '·'} ${claim.text}  \n  *${tail}.${detail}*`;
}

export function toMarkdown(graph) {
  const byId = new Map(graph.claims.map((c) => [c.id, c]));
  const repository = graph.project?.repository;
  const out = [];
  const push = (...lines) => out.push(...lines);

  push(`# ${graph.project?.title || 'Documentation'}`);
  if (graph.project?.subtitle) push('', graph.project.subtitle);

  const c = graph.coverage.counts;
  const unresolved = c.stale + c.broken + c.expired;
  if (graph.project?.proposed) {
    const pr = graph.project.proposal || {};
    push('', '> **This is a proposal. Nothing described here exists.**');
    if (pr.summary) push('>', `> ${pr.summary}`);
    const trail = [pr.by ? `Proposed by ${pr.by}` : '', pr.at ? `on ${pr.at}` : '', pr.issue ? `· ${pr.issue}` : ''].filter(Boolean).join(' ');
    if (trail) push('>', `> ${trail}`);
  }
  push('', `> Generated by ${graph.generator || 'vibex'} on ${graph.generated_at}.`
    + `${repository?.revision ? ` Checked against \`${String(repository.revision).slice(0, 7)}\`.` : ''}`);
  push('>', `> **${c.claims} claims** — ${c.verified} verified, ${c.asserted} stated`
    + `${unresolved ? `, **${unresolved} needing attention**` : ''}.`);
  push('>', '> Every statement carries its source. `✓` verified against the code · `·` stated by a person'
    + `${c.proposed ? ' · \`~\` proposed, does not exist' : ''}`
    + ' · `!` needs re-reading or out of date · `✗` unverifiable. Do not read an absence as a "no" —'
    + ' check what this document says it does not cover.');

  for (const section of graph.sections) {
    push('', `## ${section.title}`);
    if (section.summary) push('', `*${section.summary}*`);

    if (section.narrative) {
      // A citation becomes the cited claim's confidence mark, inline. No link:
      // the evidence is directly below, and cross-page anchors do not survive
      // a paste into a wiki.
      push('', section.narrative.replace(/[ \t]*\[\[([a-zA-Z][a-zA-Z0-9_.-]*)\]\]/g, (whole, id) => {
        const claim = byId.get(id);
        return claim ? ` ${MARK[claim.confidence] || '·'}` : '';
      }));
    }

    if (section.renders === 'coverage') {
      const { specs, out_of_scope: scope, unknown } = graph.coverage;
      push('', '### What was read', '');
      push(specs.length
        ? specs.map((s) => `- **${s.title}** — ${s.diagram_type}, ${s.subjects} subjects, ${s.generated ? 'facts derived from it' : 'read only to resolve references'}`).join('\n')
        : '- Nothing. No diagram specs were read, so nothing here is derived from one.');
      push('', '### Deliberately not covered', '');
      push(scope.length
        ? scope.map((o) => `- **${o.area}** — ${o.reason}`).join('\n')
        : '- Nothing is declared out of scope, so this document reads as if it covers everything. It almost certainly does not.');
      push('', '### Noticed and unaccounted for', '');
      push(unknown.length
        ? unknown.map((u) => `- **${u.what}** — ${u.why}`).join('\n')
        : '- Nothing. Every subject has at least one claim and every covered spec was read.');
    }

    const claims = section.claims.map((id) => byId.get(id)).filter(Boolean);
    if (claims.length) {
      if (section.narrative) push('', '### Evidence');
      push('', claims.map((cl) => claimBullet(cl, repository)).join('\n'));
    }
  }

  const placed = new Set(graph.sections.flatMap((s) => s.claims));
  const loose = graph.claims.filter((cl) => !placed.has(cl.id));
  if (loose.length) {
    push('', '## Also known', '', 'Claims attached to a subject but not filed under a heading.', '');
    push(loose.map((cl) => claimBullet(cl, repository)).join('\n'));
  }

  if (graph.glossary?.length) {
    push('', '## Glossary', '');
    push(graph.glossary.map((g) => `- **${g.term}** — ${g.definition}`).join('\n'));
  }

  if (unresolved) {
    push('', '## Claims that need attention', '');
    push(graph.claims.filter((cl) => ['stale', 'broken', 'expired'].includes(cl.confidence))
      .map((cl) => claimBullet(cl, repository)).join('\n'));
  }

  return `${out.join('\n')}\n`;
}
